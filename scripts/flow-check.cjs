const { fixture } = require('./entertainment-fixture.cjs')
const { chromium } = require('playwright-core')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
;(async () => {
  const f = await fixture(), out = path.resolve('dist/verification/flow'), results = [], errors = []
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ executablePath: ['C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'].find(p => fs.existsSync(p)), headless: true })
  const pass = s => { results.push(s); console.log('PASS', s) }
  try {
    await f.api(f.route('state'), 'PATCH', { client_id: randomUUID(), version: (await f.state()).version, mode: 'external', phase: 'awaiting_action' }, f.owner.cookie)
    const context = await browser.newContext({ viewport: { width: 1264, height: 900 } })
    await context.addCookies([{ name: 'linchat_session', value: f.owner.cookie.split('=')[1], url: f.url }])
    const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message))
    await page.goto(f.url + `/#campaign=${f.cid}`)
    await page.locator('.campaign-flow > summary').click()
    await page.getByText('设置行动节奏', { exact: true }).click()
    await page.getByLabel('行动处理方式').selectOption('collect')
    await page.locator('.flow-settings').getByRole('checkbox', { name: /林同学/ }).check()
    await page.locator('.flow-settings').getByRole('checkbox', { name: /小满/ }).check()
    await page.getByRole('button', { name: '保存行动节奏', exact: true }).click()
    await page.getByText('第 1 轮收集', { exact: true }).waitFor()
    pass('Owner configures explicit collection participants through the actual UI')
    await page.getByLabel('行动或叙述内容').fill('我观察钟楼')
    await page.getByRole('button', { name: '提交行动', exact: true }).click()
    await page.locator('.campaign-flow article').getByText('我观察钟楼', { exact: true }).waitFor()
    await page.getByRole('button', { name: '补充这条行动', exact: true }).click()
    await page.getByLabel('行动补充').fill('同时留意门口的脚印')
    await page.getByRole('button', { name: '发送行动补充', exact: true }).click()
    await page.locator('.campaign-flow').getByText('补充：同时留意门口的脚印', { exact: true }).waitFor()
    const agent = (await f.api(f.route('agent-tokens'), 'POST', { label: 'flow-check', secrets: false }, f.owner.cookie)).data
    async function host(route, body) {
      const response = await fetch(f.url + '/api' + f.route(route), { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${agent.token}`, 'X-LinChat': '1' }, body: JSON.stringify(body) })
      const value = await response.json(); assert.equal(response.status, 200, JSON.stringify(value)); return value
    }
    assert.equal((await host('turns/claim', {})).turn, null)
    pass('First action is visibly held; its owner appends an audited supplement; external claim cannot start early')
    await f.api(f.route('actions'), 'POST', { client_id: randomUUID(), content: '我查看门上的刻痕' }, f.player.cookie)
    await page.locator('.flow-queue').getByText('我查看门上的刻痕', { exact: true }).waitFor()
    await page.locator('.flow-queue').getByText('我观察钟楼', { exact: true }).waitFor()
    for (const width of [1264, 390, 320]) {
      await page.setViewportSize({ width, height: 900 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await page.locator('.flow-content').evaluate(e => { e.scrollTop = 0 })
      await page.screenshot({ path: path.join(out, `queue-${width}.png`) })
    }
    const { turn, context: publicContext } = await host('turns/claim', {})
    assert.equal(turn.kind, 'group')
    assert.equal(publicContext.turn_actions.length, 2)
    await page.locator('.flow-queue').getByText('主持处理中', { exact: true }).waitFor()
    assert.equal(await page.locator('.flow-queue').getByRole('button', { name: '补充这条行动', exact: true }).count(), 0)
    pass('All submissions become one joint turn with distinct actors and event IDs; claim locks further supplements')
    await host(`turns/${turn.id}/fail`, { client_id: randomUUID(), lease: turn.lease })
    await page.getByRole('button', { name: '重试并保留已掷骰', exact: true }).waitFor()
    await page.getByRole('button', { name: '重试并保留已掷骰', exact: true }).click()
    const retry = (await host('turns/claim', {})).turn
    assert.equal(retry.id, turn.id)
    await host(`turns/${retry.id}/complete`, { client_id: randomUUID(), version: retry.base_version, lease: retry.lease,
      outcome: { narration: '两人的行动已共同推进故事。', phase: 'awaiting_action', changes: [] } })
    await page.locator('.flow-queue').waitFor({ state: 'hidden' })
    pass('Failure exposes an actionable retry and keeps the same joint turn rather than duplicating the batch')
    await page.getByLabel('行动或叙述内容').fill('下一轮我先进入钟楼')
    await page.getByRole('button', { name: '提交行动', exact: true }).click()
    await page.getByRole('button', { name: '提前结束本轮收集', exact: true }).click()
    await page.getByText('只处理已提交的行动', { exact: false }).waitFor()
    assert.equal((await host('turns/claim', {})).turn, null)
    await page.getByRole('button', { name: '确认联合处理已提交行动', exact: true }).click()
    const partial = await host('turns/claim', {})
    assert.equal(partial.context.turn_actions.length, 1)
    pass('Early close requires explicit owner confirmation and never invents missing player actions')
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ version: require('../package.json').version, results, errors }, null, 2))
  } finally { await browser.close(); await f.stop() }
})().catch(e => { console.error(e); process.exitCode = 1 })
