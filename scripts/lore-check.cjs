    await page.getByText('资料已有新版本，当前文字仍保留。', { exact: false }).waitFor()
    assert.equal(await page.getByLabel('资料正文').inputValue(), '此处保留尚未保存的房主草稿。')
    assert.equal(await page.getByRole('button', { name: '保存资料', exact: true }).isDisabled(), true)
    pass('Concurrent edits surface a conflict without overwriting unsaved owner text')
