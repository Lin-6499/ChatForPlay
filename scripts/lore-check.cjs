    await page.getByLabel('供主持参考（仅公开有效资料）').check()
    await page.getByRole('button', { name: '保存资料', exact: true }).click()
    await page.getByText('已保存到战役资料', { exact: true }).waitFor()
    const read = () => f.api(f.route('lore'), 'GET', undefined, f.owner.cookie).then(r => r.data)
    let entries = await read(); assert.equal(entries.length, 1)
    const publicID = entries[0].id
    assert.equal(entries[0].in_context, true)
    const modelContext = (await f.api(f.route('context'), 'GET', undefined, f.owner.cookie)).data
    assert.ok(modelContext.lore.entries.some(e => e.id === publicID))
    pass('Markdown import is preview-only until saved; selected public chapters enter durable model context')
    await page.getByLabel('资料正文').fill('房主确认的第二版：守夜人艾文已交出钥匙，旅人尚未进入钟楼。')
