    assert.equal(await player.getByText('幕后人物的真相', { exact: true }).count(), 0)
    await player.getByText('守夜人艾文在旧钟楼等候。', { exact: false }).waitFor()
    await player.screenshot({ path: path.join(out, 'player-390.png') })
